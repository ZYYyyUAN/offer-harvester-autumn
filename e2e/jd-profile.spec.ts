import { zipSync, strToU8 } from "fflate";
async function json(response: APIResponse) { const body=await response.text(); expect(response.ok(),body).toBeTruthy(); return JSON.parse(body); }
async function create(request: APIRequestContext,jd="必须掌握 Java。\n加分项：Redis。") {
  return (await json(await request.post("/api/records",{data:{kind:"applications",data:{company:"合成科技",role:"Java后端",direction:"Java",location:"杭州",stage:"已投递",jd}}}))).record;
}
async function archive(request: APIRequestContext,id:string) { return (await json(await request.get("/api/jd/sources/"+id))).snapshots; }
async function upload(request: APIRequestContext,text="Java 项目：实现课程报名接口。") {
  const bytes=zipSync({"word/document.xml":strToU8("<w:document><w:body><w:p><w:r><w:t>"+text+"</w:t></w:r></w:p></w:body></w:document>")});
  return (await json(await request.post("/api/files?purpose=resume",{headers:{"content-type":"application/vnd.openxmlformats-officedocument.wordprocessingml.document","x-file-name":"synthetic.docx"},data:Buffer.from(bytes)}))).file;
}
