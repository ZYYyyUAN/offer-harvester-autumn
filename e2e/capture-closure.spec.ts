test("cancel followed by immediate retry cannot let an old response overwrite the new run", async ({ request }) => {
  const created = await json(await request.post("/api/job-captures", { data: { sourceUrl: "https://example.test/slow-capture-race", wait: false } }));
  const id = created.job.id;
  const oldRun = request.post(`/api/ai/jobs/${id}/run`);
  await expect.poll(async () => (await json(await request.get(`/api/ai/jobs/${id}`))).attempts.length).toBe(1);
  await json(await request.post(`/api/ai/jobs/${id}/cancel`));
  const retry = request.post(`/api/ai/jobs/${id}/retry`);
  await Promise.all([oldRun, retry]);
  const final = await json(await request.get(`/api/ai/jobs/${id}`));
  expect(final.job.status).toBe("succeeded"); expect(final.attempts).toHaveLength(2);
  expect(final.attempts.map((a: any) => a.status)).toEqual(["cancelled", "succeeded"]);
  expect(final.job.result.company).toBe("合成链接科技");
});
