test("queued captures deduplicate, concurrent run claims once, cache is explicit and refresh creates a new task", async ({ request }) => {
  const input = { sourceUrl: "https://example.test/position/1", wait: false };
  const pair = await Promise.all([request.post("/api/job-captures", { data: input }), request.post("/api/job-captures", { data: input })]);
  const [first, second] = await Promise.all(pair.map(json)); expect(first.job.id).toBe(second.job.id); expect(first.job.status).toBe("queued");
  await Promise.all([1, 2].map(() => request.post(`/api/ai/jobs/${first.job.id}/run`)));
  const audit = await json(await request.get(`/api/ai/jobs/${first.job.id}`));
  expect(audit.job.status).toBe("succeeded"); expect(audit.attempts).toHaveLength(1);
  expect(audit.attempts[0].telemetry.route).toBe("model_url"); expect(audit.attempts[0].telemetry.phases.some((p: any) => p.phase === "saving_result")).toBe(true);
  const cached = await json(await request.post("/api/job-captures", { data: input })); expect(cached.job.id).toBe(first.job.id); expect(cached.reused).toBe(true);
  const refresh = await json(await request.post("/api/job-captures", { data: { ...input, refresh: true } })); expect(refresh.job.id).not.toBe(first.job.id);
  await json(await request.post(`/api/ai/jobs/${refresh.job.id}/cancel`));
  const other = await json(await request.post("/api/job-captures", { data: { ...input, refresh: true } }));
  expect((await request.post(`/api/ai/jobs/${refresh.job.id}/retry`)).status()).toBe(409);
  await json(await request.post(`/api/ai/jobs/${other.job.id}/cancel`));
  await json(await request.post(`/api/ai/jobs/${refresh.job.id}/retry`));
  expect((await json(await request.get(`/api/ai/jobs/${refresh.job.id}`))).job.status).toBe("succeeded");
  expect((await request.get(`/api/ai/jobs/${first.job.id}`, { headers: { "oai-authenticated-user-id": "other-owner" } })).status()).toBe(404);
  const backup = await json(await request.get("/api/data/export?format=json"));
  await json(await request.delete("/api/profile?confirm=DELETE"));
  const preview = await json(await request.post("/api/data/imports", { data: { filename: "capture-v6.json", content: JSON.stringify(backup) } }));
  await json(await request.post(`/api/data/imports/${preview.importId}/commit`, { data: {} }));
  const restored = await json(await request.get("/api/data/export?format=json"));
  expect(restored.aiJobs).toEqual(backup.aiJobs); expect(restored.aiJobAttempts).toEqual(backup.aiJobAttempts);
  const outsider = { "oai-authenticated-user-id": "capture-restore-outsider" };
  const foreignPreview = await json(await request.post("/api/data/imports", { headers: outsider, data: { filename: "synthetic-shared.json", content: JSON.stringify(backup) } }));
  expect((await request.post(`/api/data/imports/${foreignPreview.importId}/commit`, { headers: outsider, data: {} })).status()).toBe(409);
  await json(await request.delete("/api/profile?confirm=DELETE", { headers: outsider }));
});
test("closure correction and reopening preserve submitted identity and historical reach", async ({ request }) => {
  const app = (await json(await request.post("/api/records", { data: { kind: "applications", data: { company: "合成闭环公司", role: "后端", stage: "面试中", jd: "掌握 Java" } } }))).record;
  const get = async () => (await json(await request.get("/api/records?kind=applications"))).records.find((r: any) => r.id === app.id);
  const closure = { cycleId: crypto.randomUUID(), outcome: "rejected", stage: "interview", round: "second", customRound: "", endedAt: "2026-11-10T02:00:00.000Z", reason: "合成拒信", notes: "", confirmation: "confirmed", source: "user", recordedAt: new Date().toISOString() };
  await json(await request.post("/api/applications/stage", { data: { id: app.id, version: app.version, stage: "已结束", closure } }));
  let current = await get(); expect(current.data.closure.cycleId).not.toBe(closure.cycleId);
  expect((await json(await request.get("/api/applications/outcomes"))).rejectedCount).toBe(1);
  const conflict = await request.post("/api/applications/stage", { data: { id: app.id, version: app.version, stage: "已结束", closure } }); expect(conflict.status()).toBe(409);
  const cycle = current.data.closure.cycleId;
  await json(await request.patch("/api/records", { data: { id: app.id, version: current.version, data: { ...current.data, closure: { ...current.data.closure, notes: "补录原因" } } } }));
  current = await get(); expect(current.data.closure.cycleId).toBe(cycle);
  await json(await request.post("/api/applications/stage", { data: { id: app.id, version: current.version, stage: "面试中" } }));
  current = await get(); expect(current.data.closure).toBeNull(); expect((await json(await request.get("/api/applications/outcomes"))).totalClosed).toBe(0);
  const events = (await json(await request.get(`/api/activity?entityId=${app.id}`))).events;
  expect(events.filter((e: any) => e.data.action === "application_closed")).toHaveLength(1);
  expect(events.filter((e: any) => e.data.action === "application_closure_corrected")).toHaveLength(1);
  expect(events.filter((e: any) => e.data.action === "application_reopened")).toHaveLength(1);
  expect((await json(await request.get("/api/data/export?format=json"))).records.filter((r: any) => r.kind === "job_submissions")).toHaveLength(1);
});

